def test_default_language_backward_compatible():
    """③ 默认语言 = 中文：不传参数行为与整改前逐字一致。"""
    print("\nTest 5: default language = Chinese, byte-identical to pre-remediation report")
    actual = _report(BASELINE_DATA)
    m = re.search(r"> 生成日期：(\d{4}-\d{2}-\d{2})", actual)
    if not check("⑤ 默认报告含生成日期行", bool(m), repr(actual[:80])):
        return False
    expected = "\n".join(EXPECTED_ZH_REPORT_LINES).replace("<DATE>", m.group(1))
    same = actual == expected
    ok = check("⑤ 默认（不传参数）报告与整改前逐字一致", same)
    if not same:
        idx = _first_diff(actual, expected)
        print("    首个差异行 #%s" % idx)
        for line in list(difflib.unified_diff(expected.splitlines(), actual.splitlines(),
                                              "整改前基线", "实际输出", lineterm=""))[:24]:
            print("    " + line)
    ok &= check("⑤ 默认输出 == 显式 --lang zh 输出（逐字）",
                actual == _report(BASELINE_DATA, "--lang", "zh"))
    ok &= check("⑤ 默认输出仍是中文报告（含中文标题）",
                actual.startswith("# 个性化职业规划报告"))
    ok &= check("⑤ 默认输出保留既有页脚", ZH_FOOTER in actual)
    return ok


