def test_language_parameter_signature():
    """① generate_report / build_recs 的语言参数存在且默认 = zh（静态 AST 断言）。"""
    print("\nTest 2: generate_report / build_recs expose a language parameter")
    with open(SCRIPT, encoding="utf-8") as f:
        src = f.read()
    tree = ast.parse(src)

    consts = {}
    for node in tree.body:
        if isinstance(node, ast.Assign):
            for tgt in node.targets:
                if isinstance(tgt, ast.Name) and isinstance(node.value, ast.Constant):
                    consts[tgt.id] = node.value.value

    funcs = {}
    for node in ast.walk(tree):
        if isinstance(node, ast.FunctionDef):
            funcs[node.name] = node

    def _default_of(node):
        """把参数默认值解析成字面量（支持 Name → 模块级常量）。"""
        if node is None:
            return None
        if isinstance(node, ast.Constant):
            return node.value
        if isinstance(node, ast.Name):
            return consts.get(node.id)
        return None

    ok = True
    ok &= check("② 模块级 DEFAULT_LANG == 'zh'（默认中文，向后兼容）",
                consts.get("DEFAULT_LANG") == "zh", repr(consts.get("DEFAULT_LANG")))
    ok &= check("② CLI --lang 选项默认值 = 'zh'（不传 --lang 即中文）",
                _cli_lang_default(tree, consts) == "zh",
                repr(_cli_lang_default(tree, consts)))

    for fn_name in ("generate_report", "build_recs"):
        fn = funcs.get(fn_name)
        if not check(f"② {fn_name} 函数存在", fn is not None):
            continue
        args = fn.args.args
        # 第一个参数是数据（data / recs），其后第一个参数即语言参数
        lang_args = [a for a in args[1:] if a.arg in ("lang", "language")]
        ok &= check(f"② {fn_name} 接受语言参数（lang / language）",
                    bool(lang_args),
                    "签名: %s" % [a.arg for a in args])
        if not lang_args:
            continue
        idx = args.index(lang_args[0])
        default = _default_of(fn.args.defaults[idx - len(fn.args.defaults)])
        ok &= check(f"② {fn_name} 语言参数默认值 = 'zh'（不传即中文）",
                    default == "zh", repr(default))
        ok &= check(f"② {fn_name} 语言参数真正驱动模板选择（喂给 normalize_lang）",
                    _lang_param_drives_body(fn, lang_args[0].arg))
    return ok


