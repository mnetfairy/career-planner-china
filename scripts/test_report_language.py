def _minimal_env(extra=None):
    """构造最小白名单环境：PATH / HOME / LANG / PYTHONPATH + 显式传入项。"""
    env = {}
    for key in MIN_ENV_KEYS:
        val = os.environ.get(key)
        if val is not None:
            env[key] = val
    env.setdefault("LANG", "C.UTF-8")
    if extra:
        env.update(extra)
    return env


def _run(args, script=None, env_extra=None, cwd=None, timeout=120):
    """跑一次脚本（只读用途）。"""
    return subprocess.run(
        ["python3", script or SCRIPT] + list(args),
        capture_output=True, text=True, timeout=timeout,
        env=_minimal_env(env_extra), cwd=cwd or SKILL_DIR,
    )


def _report(data, *extra_args):
    """用只读自省参数 --print-report 取报告 Markdown（零副作用）。

    --print-report 在任何目录创建 / 文件写入之前返回：只把 generate_report()
    的结果打到 stdout。
    """
    r = _run(["--print-report", "--data", json.dumps(data, ensure_ascii=False)]
             + list(extra_args))
    if r.returncode != 0:
        raise RuntimeError("exit=%s stderr=%s" % (r.returncode, (r.stderr or "")[:200]))
    out = r.stdout or ""
    return out[:-1] if out.endswith("\n") else out


def _first_diff(a, b):
    """返回两段文本第一处不同的行号（相同返回 -1）。"""
    la, lb = a.splitlines(), b.splitlines()
    for i in range(max(len(la), len(lb))):
        x = la[i] if i < len(la) else "<EOF>"
        y = lb[i] if i < len(lb) else "<EOF>"
        if x != y:
            return i
    return -1


def _lang_param_drives_body(fn, lang_arg_name):
    """函数体是否把语言参数喂给 normalize_lang / resolve_lang。

    只证明「参数存在」是不够的：还必须证明它**真正驱动**模板选择，
    否则「不传参数 = 中文」只是默认值好看而已。
    """
    for node in ast.walk(fn):
        if (isinstance(node, ast.Call) and isinstance(node.func, ast.Name)
                and node.func.id in ("normalize_lang", "resolve_lang")):
            for arg in node.args:
                if isinstance(arg, ast.Name) and arg.id == lang_arg_name:
                    return True
            for kw in node.keywords:
                if isinstance(kw.value, ast.Name) and kw.value.id == lang_arg_name:
                    return True
    return False


def _cli_lang_default(tree, consts):
    """取 CLI --lang 选项的默认值（None = 找不到）。"""
    for node in ast.walk(tree):
        if not (isinstance(node, ast.Call) and isinstance(node.func, ast.Attribute)
                and node.func.attr == "add_argument"):
            continue
        first = node.args[0] if node.args else None
        if not (isinstance(first, ast.Constant) and isinstance(first.value, str)):
            continue
        if not first.value.split("=")[0].startswith("--lang"):
            continue
        for kw in node.keywords:
            if kw.arg != "default":
                continue
            if isinstance(kw.value, ast.Constant):
                return kw.value.value
            if isinstance(kw.value, ast.Name):
                return consts.get(kw.value.id)
            return None
    return None


